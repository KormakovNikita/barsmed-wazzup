export function ChannelIcon({
  channel,
  className,
  variant = "brand",
}: {
  channel: Channel;
  className?: string;
  variant?: "brand" | "glyph";
}) {
  const Icon =
    variant === "glyph"
      ? CHANNEL_GLYPH_COMPONENTS[channel]
      : CHANNEL_ICON_COMPONENTS[channel];
  return <Icon className={cn("shrink-0", className)} />;
}
